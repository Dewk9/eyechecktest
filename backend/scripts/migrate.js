#!/usr/bin/env node
/**
 * Applies database/migrations/*.sql in order using SUPABASE_DB_URL.
 * Applied files are tracked in public.schema_migrations.
 *
 *   npm run db:migrate             apply pending migrations
 *   npm run db:snapshot            regenerate database/schema.sql + policies.sql from migrations
 */
import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';
import { config, PROJECT_ROOT } from '../src/config/env.js';

const DIR = path.join(PROJECT_ROOT, 'database', 'migrations');
const files = fs.readdirSync(DIR).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();

if (process.argv.includes('--snapshot')) {
  const header = (name) => `-- AUTO-GENERATED by \`npm run db:snapshot\` from database/migrations — do not edit by hand.\n-- ${name}\n\n`;
  const schema = files.filter((f) => !f.includes('policies')).map((f) => `-- >>> ${f}\n${fs.readFileSync(path.join(DIR, f), 'utf8')}`).join('\n\n');
  const policies = files.filter((f) => f.includes('policies')).map((f) => `-- >>> ${f}\n${fs.readFileSync(path.join(DIR, f), 'utf8')}`).join('\n\n');
  fs.writeFileSync(path.join(PROJECT_ROOT, 'database', 'schema.sql'), header('Full schema (tables, functions, storage, seed settings)') + schema);
  fs.writeFileSync(path.join(PROJECT_ROOT, 'database', 'policies.sql'), header('Row Level Security policies') + policies);
  console.log('Wrote database/schema.sql and database/policies.sql');
  process.exit(0);
}

if (!config.supabase.dbUrl) {
  console.error('SUPABASE_DB_URL is not set. Alternatively paste each file in database/migrations into the Supabase SQL editor in order.');
  process.exit(1);
}

const client = new pg.Client({ connectionString: config.supabase.dbUrl, ssl: { rejectUnauthorized: false } });
await client.connect();
try {
  await client.query('create table if not exists public.schema_migrations (name text primary key, applied_at timestamptz not null default now())');
  await client.query('alter table public.schema_migrations enable row level security');
  const { rows } = await client.query('select name from public.schema_migrations');
  const applied = new Set(rows.map((r) => r.name));
  for (const f of files) {
    if (applied.has(f)) { console.log(`= ${f} (already applied)`); continue; }
    const sql = fs.readFileSync(path.join(DIR, f), 'utf8');
    await client.query('begin');
    try {
      await client.query(sql);
      await client.query('insert into public.schema_migrations(name) values ($1)', [f]);
      await client.query('commit');
      console.log(`+ ${f}`);
    } catch (err) {
      await client.query('rollback');
      console.error(`✗ ${f}: ${err.message}`);
      process.exitCode = 1;
      break;
    }
  }
} finally {
  await client.end();
}
